    private void jButCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButCalcularActionPerformed
        // TODO add your handling code here:
        double sumaTiempo = 0;
        double sumaDistancia = 0;
        double sumaVelocidadI = 0;
        double sumaAceleracion = 0;
        double veloProm = 0;
        double acelProm = 0;                
        for(int r=0; r < jTableVehiculos.getRowCount();r++)
        {
            Vehiculo car = new Vehiculo();
            car.setVehiculo(jTableVehiculos.getValueAt(r, 0) + "");
            car.setDistancia(Double.parseDouble(jTableVehiculos.getValueAt(r, 1) + ""));
            car.setVelocidadI(Double.parseDouble(jTableVehiculos.getValueAt(r, 2) + ""));
            car.setAceleracion(Double.parseDouble(jTableVehiculos.getValueAt(r, 3) + ""));            
            jTableVehiculos.setValueAt(formato.format(car.calcTiempo()), r, 4);
            
            
            sumaDistancia += car.getDistancia();
            sumaVelocidadI += car.getVelocidadI();
            sumaAceleracion += car.getAceleracion();
            sumaTiempo += car.calcTiempo();
            
            veloProm = sumaVelocidadI / jTableVehiculos.getRowCount();
            acelProm = sumaAceleracion / jTableVehiculos.getRowCount();
        }
        jTablePromedios.setValueAt(formato.format(sumaDistancia), 0, 1);
        jTablePromedios.setValueAt(formato.format(veloProm), 0, 2);
        jTablePromedios.setValueAt(formato.format(acelProm), 0, 3);
        jTablePromedios.setValueAt(formato.format(sumaTiempo), 0, 4);
        

    }//GEN-LAST:event_jButCalcularActionPerformed

    private void jButOrdenarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButOrdenarActionPerformed
        // TODO add your handling code here:

        Vehiculo[] lista = new Vehiculo[jTableVehiculos.getRowCount()];
        
        for(int r = 0; r < jTableVehiculos.getRowCount(); r++)
        {
            Vehiculo carr = new Vehiculo(); // crea un objeto nuevo en cada iteracion
            
            carr.setVehiculo(jTableVehiculos.getValueAt(r, 0) + "");
            carr.setDistancia(Double.parseDouble(jTableVehiculos.getValueAt(r, 1) + ""));
            carr.setVelocidadI(Double.parseDouble(jTableVehiculos.getValueAt(r, 2) + ""));
            carr.setAceleracion(Double.parseDouble(jTableVehiculos.getValueAt(r, 3) + ""));            
            jTableVehiculos.setValueAt(formato.format(carr.calcTiempo()), r, 4);
            
            // asignamos el objeto en la posicion r del arreglo
            lista [r] = carr;
        }
      
     // Usaremos el metodo de la burbuja
     // Primero agrego el ordenamiento alfabetico y luego el de tiempo para que los acomode por letra en caso de ser el mismo valor numerico
     for(int i=0; i < lista.length - 1; i++)
            for(int j= i+1; j < lista.length; j++)
                if(lista[i].getVehiculo().compareTo(lista[j].getVehiculo()) > 0){ // < = descendente   > = ascendente
                    Vehiculo veh = lista[i];
                    lista[i] = lista[j];
                    lista[j] = veh;
                }
     
     
        for(int i=0; i < lista.length - 1; i++)
            for(int j= i+1; j < lista.length; j++)
                if(lista[i].calcTiempo()< lista[j].calcTiempo()){ // < = descendente   > = ascendente
                    Vehiculo veh = lista[i];
                    lista[i] = lista[j];
                    lista[j] = veh;
                }
        
        //regresamos lo datos ya ordenados del jTable
        
        for(int r = 0; r < jTableVehiculos.getRowCount(); r++)
        {
            jTableVehiculos.setValueAt(lista[r].getVehiculo(), r, 0);
            jTableVehiculos.setValueAt(lista[r].getDistancia(), r, 1);
            jTableVehiculos.setValueAt(lista[r].getVelocidadI(), r, 2);
            jTableVehiculos.setValueAt(lista[r].getAceleracion(), r, 3);
            jTableVehiculos.setValueAt(formato.format(lista[r].calcTiempo()), r, 4);
        }
        


        
    }//GEN-LAST:event_jButOrdenarActionPerformed

