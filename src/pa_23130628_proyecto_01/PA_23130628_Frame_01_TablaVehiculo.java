    private void jButMayorMenorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButMayorMenorActionPerformed
        // TODO add your handling code here:
        Vehiculo mayor = new Vehiculo();
        Vehiculo menor = new Vehiculo();
        for(int r = 0; r < jTableVehiculos.getRowCount(); r++)
        {
            Vehiculo carr = new Vehiculo(); 
            
            carr.setVehiculo(jTableVehiculos.getValueAt(r, 0) + "");
            carr.setDistancia(Double.parseDouble(jTableVehiculos.getValueAt(r, 1) + ""));
            carr.setVelocidadI(Double.parseDouble(jTableVehiculos.getValueAt(r, 2) + ""));
            carr.setAceleracion(Double.parseDouble(jTableVehiculos.getValueAt(r, 3) + ""));            
            jTableVehiculos.setValueAt(formato.format(carr.calcTiempo()), r, 4);
            
            if(r==0){
                mayor = carr;
                menor = carr;
            }
            
            if(carr.calcTiempo() > mayor.calcTiempo())
                mayor = carr;
            if(carr.calcTiempo() < menor.calcTiempo())
                menor = carr;
            
        }
        
        jLabMayor.setText(mayor.getVehiculo());
        jLabMenor.setText(menor.getVehiculo());
    }//GEN-LAST:event_jButMayorMenorActionPerformed

